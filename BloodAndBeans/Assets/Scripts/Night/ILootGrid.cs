/// 칸 그리드 UI가 읽는 것 (기획서 6.5.4 「아이템 박스 UI의 재사용」).
///
/// 기획서가 같은 그리드를 네 곳에서 쓴다고 정했다 — 숲의 상자(본체), 견제로 흘린
/// 재료(6.6), 쏟은 배낭(6.7), 그리고 **낮의 재료 칸**. 앞의 셋은 전부 `ItemBox`라
/// 구현이 하나였고, 낮의 재료 칸(`IngredientShelf`)이 붙으면서 두 번째가 생겼다.
/// 그래서 지금 이 계약이 있다 — 구현이 하나뿐일 때 미리 만들어 두는 것이 아니다
/// (AGENTS.md 「C# 코드 설계에서 쓰지 말아야 할 방식」).
///
/// 담는 행위는 여기 없다. 상자는 `PlayerInteract`를 거쳐 소유자 검증을 받고 재료 칸은
/// 자기 RPC로 보내는데, 둘의 검증 근거가 서로 달라서 한 메서드로 묶으면 어느 쪽이든
/// 남의 검증을 빌려 쓰게 된다. 창은 「몇 번째 칸을 눌렀다」만 콜백으로 돌려준다.
public interface ILootGrid
{
    /// 칸 수. 상자는 종류 기준 최대 5개고(6.5.5) 재료 칸은 선반이 내주는 재료 수다.
    int SlotCount { get; }

    Ingredient SlotItem(int index);

    /// 그 칸에 몇 개 있는가. `0`이면 비었고, **`-1`은 무제한**이다 — 상비 재료와
    /// 무한 공급 설비가 대는 재료가 그렇다 (기획서 7.1, 8장).
    int SlotCountAt(int index);

    /// 앞에서부터 몇 칸이 정체를 드러냈는가 (기획서 6.5.5의 순차 공개). 가릴 것이 없는
    /// 그리드는 `SlotCount`를 그대로 돌려준다.
    int RevealedCount { get; }

    /// 창 머리에 쓸 한 줄. 상자는 등급, 재료 칸은 자기 이름이다.
    string GridTitle { get; }

    /// 창 바닥에 쓸 한 줄. 이 그리드가 어떻게 닫히는지를 알린다.
    string GridHint { get; }
}
